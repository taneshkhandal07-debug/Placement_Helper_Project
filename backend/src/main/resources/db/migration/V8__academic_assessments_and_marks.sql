-- 1. Academic Assignments
CREATE TABLE academic_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
    section_id BIGINT NOT NULL REFERENCES sections(id) ON DELETE CASCADE,
    faculty_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    attachment_url VARCHAR(255),
    due_date TIMESTAMP NOT NULL,
    max_marks DECIMAL(5,2) NOT NULL DEFAULT 100.00,
    allow_late_submission BOOLEAN DEFAULT TRUE,
    late_penalty_percentage DECIMAL(4,2) DEFAULT 10.00,
    status VARCHAR(30) NOT NULL DEFAULT 'PUBLISHED',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Student Submissions
CREATE TABLE academic_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES academic_assignments(id) ON DELETE CASCADE,
    student_enrollment_id BIGINT NOT NULL REFERENCES student_enrollments(id) ON DELETE CASCADE,
    submission_text TEXT,
    file_url VARCHAR(255),
    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_late BOOLEAN DEFAULT FALSE,
    marks_obtained DECIMAL(5,2),
    feedback TEXT,
    graded_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    graded_at TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'SUBMITTED',
    CONSTRAINT uq_assignment_student UNIQUE (assignment_id, student_enrollment_id)
);

-- 3. Academic Scheduled Assessments (In-Sem, End-Term, Practical)
CREATE TABLE academic_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
    semester_id BIGINT NOT NULL REFERENCES semesters(id) ON DELETE CASCADE,
    section_id BIGINT REFERENCES sections(id) ON DELETE CASCADE,
    faculty_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    assessment_type VARCHAR(50) NOT NULL,
    weightage_percent DECIMAL(5,2) DEFAULT 20.00,
    max_marks DECIMAL(5,2) NOT NULL,
    passing_marks DECIMAL(5,2) NOT NULL,
    assessment_date DATE NOT NULL,
    is_published BOOLEAN DEFAULT FALSE,
    published_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. Academic Student Marks / Exam Results
CREATE TABLE academic_marks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES academic_assessments(id) ON DELETE CASCADE,
    student_enrollment_id BIGINT NOT NULL REFERENCES student_enrollments(id) ON DELETE CASCADE,
    marks_obtained DECIMAL(5,2) NOT NULL,
    is_absent BOOLEAN DEFAULT FALSE,
    remarks VARCHAR(255),
    graded_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    graded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_assessment_student_mark UNIQUE (assessment_id, student_enrollment_id)
);

-- 5. Academic Marks Audit Log (Traceable result corrections)
CREATE TABLE academic_marks_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mark_id BIGINT NOT NULL REFERENCES academic_marks(id) ON DELETE CASCADE,
    previous_marks DECIMAL(5,2),
    new_marks DECIMAL(5,2) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    changed_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

