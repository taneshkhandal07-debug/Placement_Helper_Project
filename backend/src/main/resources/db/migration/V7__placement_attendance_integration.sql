-- 2. Placement Participations (Verified Physical/Virtual Drive Check-In)
CREATE TABLE placement_participations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upcoming_drive_id BIGINT NOT NULL REFERENCES upcoming_drives(id) ON DELETE CASCADE,
    student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    check_in_time TIMESTAMP,
    check_out_time TIMESTAMP,
    verification_status VARCHAR(30) NOT NULL DEFAULT 'REGISTERED',
    verified_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    verified_at TIMESTAMP,
    verification_method VARCHAR(50),
    remarks VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_drive_student UNIQUE (upcoming_drive_id, student_user_id)
);

-- 3. Placement Schedule Conflicts (Advance conflict detection with classes and CRT)
CREATE TABLE placement_schedule_conflicts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upcoming_drive_id BIGINT NOT NULL REFERENCES upcoming_drives(id) ON DELETE CASCADE,
    student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    conflict_type VARCHAR(30) NOT NULL,
    session_description VARCHAR(255) NOT NULL,
    conflict_date DATE NOT NULL,
    conflict_start TIME NOT NULL,
    conflict_end TIME NOT NULL,
    faculty_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    student_notified BOOLEAN DEFAULT FALSE,
    faculty_notified BOOLEAN DEFAULT FALSE,
    detected_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. Placement Duty Exemptions (Distinct academic duty record linking to class or CRT)
CREATE TABLE placement_duty_exemptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participation_id BIGINT NOT NULL REFERENCES placement_participations(id) ON DELETE CASCADE,
    student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    target_type VARCHAR(30) NOT NULL,
    attendance_record_id BIGINT REFERENCES attendance_records(id) ON DELETE SET NULL,
    crt_attendance_record_id BIGINT REFERENCES crt_attendance_records(id) ON DELETE SET NULL,
    conflict_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    original_status VARCHAR(30),
    exemption_status VARCHAR(30) NOT NULL DEFAULT 'GRANTED',
    duty_policy_code VARCHAR(50) DEFAULT 'INST_PLACEMENT_DUTY_V1',
    approved_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    approved_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    remarks VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 5. Audit Trail for All Integration Operations
CREATE TABLE placement_integration_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(50) NOT NULL,
    entity_id BIGINT NOT NULL,
    action VARCHAR(50) NOT NULL,
    previous_state TEXT,
    new_state TEXT,
    performed_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

