-- =========================================================================
-- Flyway Migration V6: Campus Recruitment Training (CRT) Management
-- Strict module boundary: completely separate from regular academic attendance
-- =========================================================================

CREATE TABLE crt_tracks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE crt_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    academic_year_id BIGINT NOT NULL REFERENCES academic_years(id) ON DELETE CASCADE,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    capacity INT DEFAULT 120,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE crt_batch_trainers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES crt_batches(id) ON DELETE CASCADE,
    trainer_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    track_id BIGINT NOT NULL REFERENCES crt_tracks(id) ON DELETE CASCADE,
    role_title VARCHAR(50) DEFAULT 'LEAD_TRAINER',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_crt_batch_trainer_track UNIQUE (batch_id, trainer_user_id, track_id)
);

CREATE TABLE crt_enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    academic_year_id BIGINT NOT NULL REFERENCES academic_years(id) ON DELETE CASCADE,
    batch_id BIGINT REFERENCES crt_batches(id) ON DELETE SET NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',
    opt_in_notes TEXT,
    opted_in_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    verified_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    verified_at TIMESTAMP,
    verification_remarks VARCHAR(255),
    CONSTRAINT uq_student_year_crt UNIQUE (student_user_id, academic_year_id)
);

CREATE TABLE crt_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES crt_batches(id) ON DELETE CASCADE,
    track_id BIGINT NOT NULL REFERENCES crt_tracks(id) ON DELETE CASCADE,
    trainer_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    session_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    topic VARCHAR(255) NOT NULL,
    location_or_link VARCHAR(255),
    status VARCHAR(30) DEFAULT 'SCHEDULED',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_crt_session UNIQUE (batch_id, track_id, session_date, start_time)
);

CREATE TABLE crt_attendance_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES crt_sessions(id) ON DELETE CASCADE,
    student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status VARCHAR(30) NOT NULL,
    remarks VARCHAR(255),
    recorded_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_crt_session_student UNIQUE (session_id, student_user_id)
);

CREATE TABLE crt_attendance_corrections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id BIGINT NOT NULL REFERENCES crt_attendance_records(id) ON DELETE CASCADE,
    student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    requested_status VARCHAR(30) NOT NULL,
    reason TEXT NOT NULL,
    status VARCHAR(30) DEFAULT 'PENDING',
    reviewed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    reviewer_remarks VARCHAR(255),
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE crt_attendance_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id BIGINT NOT NULL REFERENCES crt_attendance_records(id) ON DELETE CASCADE,
    action VARCHAR(50) NOT NULL,
    previous_status VARCHAR(30),
    new_status VARCHAR(30) NOT NULL,
    performed_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE crt_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES crt_batches(id) ON DELETE CASCADE,
    track_id BIGINT NOT NULL REFERENCES crt_tracks(id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    assessment_date DATE NOT NULL,
    max_marks NUMERIC(5, 2) NOT NULL,
    pass_percentage NUMERIC(5, 2) DEFAULT 60.00,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE crt_assessment_scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES crt_assessments(id) ON DELETE CASCADE,
    student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    marks_obtained NUMERIC(5, 2) NOT NULL,
    remarks VARCHAR(255),
    graded_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    graded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_crt_assessment_student UNIQUE (assessment_id, student_user_id)
);

